def _words(rng: random.Random, n: int) -> str:
    return " ".join(rng.choice(_WORDS) for _ in range(n))


def rag_prompts(order: str, count: int, seed: int) -> list[str]:
    """`count` prompts over the same retrieved passages, one new question each.

    "ranked" shuffles the passages per request, as a retriever's scores would; "sorted" keeps
    them in document-id order.
    """
    rng = random.Random(seed)
    instructions = _words(rng, RAG_INSTRUCTIONS)
    passages = [f"Document {i + 1}: {_words(rng, RAG_PASSAGE_LEN)}" for i in range(RAG_PASSAGES)]
    prompts = []
    for _ in range(count):
        picked = list(range(RAG_PASSAGES))
        if order == "ranked":
            rng.shuffle(picked)
        body = "\n\n".join(passages[i] for i in picked)
        prompts.append(f"{instructions}\n\n{body}\n\nQuestion: {_words(rng, RAG_QUESTION)}")
    return prompts
